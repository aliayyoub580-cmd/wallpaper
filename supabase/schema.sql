-- Run this SQL in Supabase SQL Editor
create extension if not exists "pgcrypto";

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  slug text not null unique,
  description text,
  icon text,
  parent_id bigint references public.categories(id) on delete set null,
  created_at timestamptz not null default now()
);

alter table public.categories add column if not exists description text;
alter table public.categories add column if not exists icon text;
alter table public.categories add column if not exists parent_id bigint references public.categories(id) on delete set null;

create table if not exists public.users (
  id uuid primary key,
  name text,
  email text unique not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.admins (
  id uuid primary key,
  name text not null,
  email text unique not null,
  password text not null,
  is_admin boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.wallpapers (
  id uuid primary key default gen_random_uuid(),
  filename text unique,
  title text not null,
  description text,
  image_url text not null,
  mime text,
  size bigint not null default 0,
  width integer not null default 0,
  height integer not null default 0,
  category_folder text,
  storage_path text not null unique,
  user_id uuid not null references auth.users(id) on delete cascade,
  views integer not null default 0,
  likes_count integer not null default 0,
  downloads integer not null default 0,
  created_at timestamptz not null default now()
);

alter table public.wallpapers add column if not exists filename text;
alter table public.wallpapers add column if not exists mime text;
alter table public.wallpapers add column if not exists size bigint not null default 0;
alter table public.wallpapers add column if not exists width integer not null default 0;
alter table public.wallpapers add column if not exists height integer not null default 0;
alter table public.wallpapers add column if not exists downloads integer not null default 0;
alter table public.wallpapers add column if not exists category_folder text;

create table if not exists public.wallpaper_categories (
  wallpaper_id uuid not null references public.wallpapers(id) on delete cascade,
  category_id bigint not null references public.categories(id) on delete cascade,
  primary key (wallpaper_id, category_id)
);

create table if not exists public.wallpaper_likes (
  id bigint generated by default as identity primary key,
  wallpaper_id uuid not null references public.wallpapers(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique (wallpaper_id, user_id)
);

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  type text not null,
  title text not null,
  message text not null,
  wallpaper_id uuid references public.wallpapers(id) on delete set null,
  from_user_id uuid references auth.users(id) on delete set null,
  read boolean not null default false,
  created_at timestamptz not null default now()
);

