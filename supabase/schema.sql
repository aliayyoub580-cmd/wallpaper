-- Public read policies
drop policy if exists "public can read categories" on public.categories;
create policy "public can read categories"
  on public.categories
  for select
  using (true);

drop policy if exists "public can read users" on public.users;
create policy "public can read users"
  on public.users
  for select
  using (true);

drop policy if exists "public can read admins" on public.admins;
create policy "public can read admins"
  on public.admins
  for select
  using (false);

drop policy if exists "public can read wallpapers" on public.wallpapers;
create policy "public can read wallpapers"
  on public.wallpapers
  for select
  using (true);

drop policy if exists "public can read wallpaper category links" on public.wallpaper_categories;
create policy "public can read wallpaper category links"
  on public.wallpaper_categories
  for select
  using (true);

-- Authenticated write policies
drop policy if exists "authenticated can create wallpapers" on public.wallpapers;
create policy "authenticated can create wallpapers"
  on public.wallpapers
  for insert
  to authenticated
  with check (auth.uid() = user_id);

drop policy if exists "owner can update own wallpapers" on public.wallpapers;
create policy "owner can update own wallpapers"
  on public.wallpapers
  for update
  to authenticated
  using (auth.uid() = user_id);

drop policy if exists "owner can delete own wallpapers" on public.wallpapers;
create policy "owner can delete own wallpapers"
  on public.wallpapers
  for delete
  to authenticated
  using (auth.uid() = user_id);

drop policy if exists "authenticated can link categories" on public.wallpaper_categories;
create policy "authenticated can link categories"
  on public.wallpaper_categories
  for insert
  to authenticated
  with check (true);

drop policy if exists "authenticated can like" on public.wallpaper_likes;
create policy "authenticated can like"
  on public.wallpaper_likes
  for insert
  to authenticated
  with check (auth.uid() = user_id);

drop policy if exists "owner can unlike" on public.wallpaper_likes;
create policy "owner can unlike"
  on public.wallpaper_likes
  for delete
  to authenticated
  using (auth.uid() = user_id);

drop policy if exists "owner can read notifications" on public.notifications;
create policy "owner can read notifications"
  on public.notifications
  for select
  to authenticated
  using (auth.uid() = user_id);

drop policy if exists "owner can update notifications" on public.notifications;
create policy "owner can update notifications"
  on public.notifications
  for update
  to authenticated
  using (auth.uid() = user_id);

drop policy if exists "service role can insert notifications" on public.notifications;
create policy "service role can insert notifications"
  on public.notifications
  for insert
  to authenticated
  with check (auth.uid() = user_id);
